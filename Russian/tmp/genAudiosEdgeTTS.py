VOICE = "ru-RU-SvetlanaNeural"  # Voz femenina rusa de alta calidad
OUTPUT_DIR = "audio_edge"

async def generate_audio(phrase, filename):
    communicate = edge_tts.Communicate(phrase, VOICE)
    await communicate.save(filename)

def sanitize_filename(text):
    return re.sub(r'[\\/*?:"<>|]', '', text).strip()

async def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    for phrase in phrases:
        safe_phrase = sanitize_filename(phrase)
        filename = f"tts_ru_{safe_phrase}.mp3"
        filepath = os.path.join(OUTPUT_DIR, filename)
        if os.path.exists(filepath):
            print(f"Ya existe: {filename}")
            continue
        print(f"Generando: {phrase} -> {filename}")
        try:
            await generate_audio(phrase, filepath)
        except Exception as e:
            print(f"Error con '{phrase}': {e}")
        await asyncio.sleep(0.5)  # pequeña pausa

if __name__ == "__main__":
    asyncio.run(main())
    print(f"\nAudios generados en {OUTPUT_DIR}/")
